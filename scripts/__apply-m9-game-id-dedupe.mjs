function lines(values) {
  return `${values.join('\n')}\n`;
}

function assertBlob(filePath) {
  const actual = execFileSync('git', ['hash-object', filePath], {
    encoding: 'utf8',
  }).trim();
  const expected = EXPECTED_BLOBS[filePath];
  if (actual !== expected) {
    throw new Error(
      `${filePath} blob drifted: expected ${expected}, received ${actual}.`,
    );
  }
}

function replaceOnce(source, before, after, label) {
  const first = source.indexOf(before);
  if (first === -1 || source.indexOf(before, first + before.length) !== -1) {
    throw new Error(`${label} must match exactly once.`);
  }
  return `${source.slice(0, first)}${after}${source.slice(first + before.length)}`;
}

